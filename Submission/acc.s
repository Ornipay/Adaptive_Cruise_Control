;=================================================================================================================================;
	.data
;=================================================================================================================================;



;=================================================================================================================================;
	.text

	.global acc
	.global acc_init
	.global timer_interrupt_init
	.global Timer0A_Handler

U0FR: 	.equ 0x18
DIR:	.equ 0x400
DEN:	.equ 0x51C
DATA:	.equ 0x3FC
EN0: 	.equ 0x100
CLK: 	.equ 0x608

RCGCTIMER:	.equ 0x604
RCGCGPIO:   .equ 0x608
RCGCSSI:    .equ 0x61C

GPTMCTL: 	.equ 0x00C
GPTMIMR:	.equ 0x018
GPTMICR:	.equ 0x024
GPTMTAMR:	.equ 0x004
GPTMTAILR:	.equ 0x028

GPIODIR:    .equ 0x400
GPIODEN:    .equ 0x51C
GPIOAFSEL:  .equ 0x420
GPIOPCTL:   .equ 0x52C
GPIODATA:   .equ 0x3FC
;=================================================================================================================================;



;=================================================================================================================================;
acc:
	PUSH {r4-r12, lr}

	BL acc_init									; initialize ACC
	BL timer_interrupt_init						; initialize timer

acc_loop:
	B acc_loop

acc_exit:
	POP {r4-r12, lr}
	MOV pc, lr
;=================================================================================================================================;



;=================================================================================================================================;
acc_init:
	PUSH {r4-r12, lr}


	POP {r4-r12, lr}
	MOV pc, lr
;=================================================================================================================================;


;=================================================================================================================================;
Timer0A_Handler:
	PUSH {r4-r12, lr}

	; clear interrupt flag
	MOV r4, #0x0000
	MOVT r4, #0x4003
	LDRB r5, [r4, #0x024]
	ORR r5, r5, #0x01
	STRB r5, [r4, #0x024]


	POP {r4-r12, lr}
	BX lr
;=================================================================================================================================;



;========================================================================================;
	.end
;========================================================================================;
